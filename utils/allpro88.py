class volt(float):
	"""
	Sub-class of float used to indicate to a DAC proxy that the value
	should be interpreted as a voltage, not a DAC count.

	Example:

	>>> programmer.vadj = 128	# set VADJ DAC register to 128
	>>> programmer.vadj = volt(20)	# set VADJ to 20 V using cal model
	"""
	pass


class dacregister(object):
	"""
	Write a value to a DAC register.  Provides type conversion and
	range checking to ensure the value written is allowed, and will
	optionally apply a volts-to-DAC count calibration function.
	"""
	def __init__(self, address = None, transient = 0.):
		# DAC register address.  if the object to which this
		# descriptor is attached has a .dac_address attribute, then
		# its value will be used instead of this.

		self.dac_address = address

		# transient response time in seconds.  for convenience,
		# this code can enforce a pause after changing a DAC, to
		# give the respective voltage time to slew.  this removes
		# the need to include those pauses in calling code
		# everywhere they are required.
		#
		# NOTE:  it is possible, and often convenient, to set
		# various DACs before turning on the power supplies that
		# drive the DACs, so that when power is applied the pins of
		# a part ramp up in voltage together.  obviously when that
		# is done the pause that should be included to allow for
		# voltage slews needs to be inserted when the power
		# supplies are turned on, not when the DAC register is set.
		# with that example in mind, the inclusion of the transient
		# pause feature here does not guarantee that all voltage
		# slew pauses associated with a given DAC are necessarily
		# accounted for.  thought should always be put into where a
		# delay might still be needed.

		self.transient = transient

	def __set_name__(self, owner, name):
		self.name = name

	def calfunc(self, obj):
		"""
		Retrieve the calibration curve for this DAC.  The object
		obj must have a dictionary named .cal containing an entry
		whose key equals the name of this descriptor.  For example
		an object with a dacdescriptor attribute named .vadj must
		also have a .cal attribute contraining a dictionary with a
		"vadj" entry providing the calibration function.
		"""
		return obj.cal[self.name]

	def cal(self, dac, obj):
		"""
		Convert DAC count to voltage.  .calfunc() is called on obj
		to retrieve the calibration function, which is passed an
		integer DAC count, and which must return the corresponding
		voltage in volts.
		"""
		return self.calfunc(obj)(dac)

	def __set__(self, obj, val):
		"""
		Set the DAC register.  If the value is a volt object, the
		calibration function is applied to convert the voltage to
		an integer count, which is then written to the DAC
		register.  Otherwise, the value supplied is converted to an
		integer, and then written to the DAC register.  In both
		cases, before writing the integer DAC count to the register
		it is confirmed to be in [0, 255].  If any of the
		conversion steps or safety checks fail, an exception will
		be raised, typically ValueError, but OverflowError and
		others are possible depending on the nature of the failure.
		"""
		# if the calling code has given us a volt value, convert to
		# DAC count
		if type(val) is volt:
			dac = self.invcal(val, obj)
		else:
			# verify int compatibility
			dac = int(val)
		# verify range
		if not 0 <= dac <= 255:
			raise ValueError("0 <= dac <= 255:  %d" % dac)
		# determine address of DAC register.  if the object to
		# which we are attached provides a .dac_address attribute,
		# then we use its value, otherwise we use the address given
		# to .__init__().
		address = obj.dac_address if hasattr(obj, "dac_address") else self.dac_address
		# write the value and pause for transient
		obj.write_addr(address, dac)
		time.sleep(self.transient)

	def invcal(self, v, obj):
		"""
		Convert voltage to DAC count.  Uses a bisection search to
		invert the .cal() method and returns the integer DAC count
		value that most closely approximates the requested voltage.
		Raises ValueError if the requested voltage is above the
		highest voltage of the DAC.  Voltages that are below the
		limits of the DAC are mapped to the lowest available
		voltage.
		"""
		# retrieve the forward (DAC -> volts) calibration function
		calfunc = self.calfunc(obj)
		# most DAC-to-voltage calibration mappings are linear or
		# quadratic polynomials, with a cut-off at the low end
		# below which the voltage is a constant.  rather than
		# constructing a generic inverse of such functions, because
		# the number of possible values is so small, we use a
		# bisection search to invert the calibration by
		# brute-force.  this loop's worst case completes in just 8
		# iterations, and doing it this way has the advantage of
		# always working for any DAC-to-voltage calibration mapping
		# whose slope doesn't change sign.
		lo, hi = 0, 256
		if v >= self.cal(255.5, obj):
			raise ValueError("voltage too high:  requested %g V > DAC limit of %g V" % (v, self.cal(255, obj)))
		while hi - lo > 0.5:
			mid = (hi + lo) / 2
			cal = calfunc(mid)
			if cal == v:
				dac = mid
				break
			elif cal < v:
				lo = mid
			else:	# cal > v:
				hi = mid
		else:
			dac = lo
		# can't use round() because it rounds half odd integers up
		# but half even integers douwn.  round(1.5) == round(2.5).
		# perhaps if we extended the loop until hi-lo <= 0.25 and
		# then used round() it would be, statistically speaking, a
		# better inverse, but *this* algorithm, with the loop above
		# as-is and the rounding below as-is produces the answers I
		# want when tested against actual example calibration
		# curves.
		dac = min(255, math.floor(dac + 0.5))
		assert type(dac) is int and 0 <= dac <= 255
		# some calibration mappings predict a constant output below
		# some threshold.  if we've chosen a DAC setting in such an
		# interval, choose the lowest such DAC setting (typically
		# 0, but check).
		while dac > 0 and calfunc(dac - 1) == calfunc(dac):
			dac -= 1
		return dac


class channel_proxy(object):
	"""
	An interface to the capabilities of a single pin driver channel.
	Features include setting the configuration of the pin, measuring
	the voltage on a pin, comparing that voltage to a threshold,
	briefly pulsing the pin and enabling and disabling the pin's bypass
	capacitor.
	"""
	def __init__(self, programmer, channel):
		# allpro88 instance with which we are associated
		self.programmer = programmer
		# integer channel number
		if not 0 <= channel <= 87:
			raise ValueError(channel)
		self.channel = channel
		# start address of register group for this channel
		if self.channel <= 0x27:
			self.address = self.channel << 4
		else:
			self.address = (self.channel + 0x18) << 4
		# this channel's DAC address.  this attribute is used by
		# the .vdac descriptor
		self.dac_address = self.address + 3
		# bypass capacitor control register
		# FIXME:  the bypass capacitor feature including its
		# associated control logic and address decode circuitry
		# lives on the socket module.  it's not part of the
		# programmer.  if a different socket module gets installed
		# who knows what these addresses would control.  this
		# address range is probably meant to be a generic expansion
		# port feature, and it would probably be better being
		# handled by the socket_module class somehow so that the
		# correct code is attached to the electronics.
		if channel <= 0x27:
			self.bypass_address = 0x280 + channel
		elif channel <= 0x2f:
			self.bypass_address = 0x2c0 + (channel - 0x28)
		else:
			# only first 48 channels have bypass capacitors
			self.bypass_address = None
		# set default calibration
		self.set_cal()

	config = property(fset = lambda self, config: self.programmer.write_addr(self.address, config), doc = """
	Write only access to pin configuration register.  See PINCON for
	values.
	""")

	vdac = dacregister()

	def write_addr(self, *args, **kwargs):
		"""
		Synonym of self.programmer.write_addr().  This is plumbing
		for internal use by the dacregister code.
		"""
		return self.programmer.write_addr(*args, **kwargs)

	def set_cal(self, cal_data = {"min": 0.19, "poly": (-0.7, 0.1)}):
		"""
		Set the calibration model for this channel's VDAC DAC.  If
		cal_data is not set, a default calibration model is used.

		The calibration model is a dictionary providing a minimum
		output voltage and a polynomial mapping DAC count to output
		voltage (above the minimum).  The programmer's power
		supplies and DACs are calibrated at the factory to provide
		a nominal ratio of 0.1 V per DAC count.  The pin driver
		VDAC output circuitry includes an emitter-follower silicon
		power transistor and a Shottky reverse protection diode,
		which together reduce the output voltage by about 0.7 V.
		The default calibration is, therefore, 0.1 V/count - 0.7 V
		above a minimum of 0.19 V.
		"""
		poly = numpy.polynomial.Polynomial(cal_data["poly"])
		# this dictionary attribute is used by the .vdac descriptor
		self.cal = {
			"vdac": (lambda dac: max(cal_data["min"], poly(dac)))
		}

	def __bool__(self):
		"""
		State of this channel's comparator:  1 = voltage on pin is
		above VTH;  0 = voltage on pin is below VTH.

		NOTE:  with VTH and pin driver power supplies off, in
		some units the comparator reports logic 0 while in others
		it reports logic 1.  In the two examples I have access to,
		the behaviour is consistent across all channels:  they
		either all report 0 in this configuration or all report 1,
		which suggests that the behaviour is not due to random
		fluctuations in comparator behaviour, but is a circuit
		design choice that ensures one or the other results, and
		that there was a revision in this feature at some point.
		"""
		return bool(self.programmer.read_addr(self.address) & 1)

	def measure_v(self, n = 1):
		"""
		Use a bisection search with VTH to measure the voltage on
		this channel's pin.  Repeat the measurement n times
		(default = 1) and report the median of the measurements.
		NOTE:  VTH is left set to (an approximation of) the
		measured voltage.
		"""
		n = int(n)
		assert n > 0
		volts = []
		for i in range(n):
			dac, = self.programmer.write_command("M%02X" % self.channel)
			volts.append(self.programmer.vth.cal(dac, self.programmer))
		return numpy.median(volts)

	def pulse(self, microseconds, config, final_config):
		"""
		Switch this channel's configuration to config, hold it for
		the given number of microseconds, then switch the
		configuration to final_config.

		It is common for programmable devices to require a short
		pulse on a single pin to affect the programming operation.
		Usually there are strict requirements for the duration of
		the pulse.  This method is provided to meet the needs of
		such parts.  The pulse is generated by the USB interface's
		firmware, using a precision timing loop.

		ValueError is raised if the requested pulse duration is
		outside the range [0 us, 65535 us].

		NOTE:  the shortest pulse the firmware can generate is
		approximately 5 us.  It is not an error to request a
		shorter pulse, but a 5 us pulse will be generated in those
		cases.
		"""
		microseconds = int(microseconds)
		if microseconds < 0:
			raise ValueError("pulse duration < 0")
		if microseconds > 0xffff:
			# FIXME:  if such a long pulse, longer than ~65 ms,
			# is desired then probably also the duration does
			# not need to be controled with microsecond
			# accuracy.  if the tolerance can be relaxed
			# enough, the pulse could be implemented in
			# software, here, on the host side.
			raise ValueError("pulse duration too long:  %d us" % microseconds)
		self.programmer.write_command("P%02X%04X%02X%02X" % (self.channel, microseconds, config, final_config))

	@property
	def bypass(self):
		"""
		Write-only boolean to set the state of this channels'
		bypass capacitor.  True = enabled.  Not all channels have
		bypass capacitors.  It is not an error to attempt to enable
		or disable the bypass capacitor of a channel that does not
		have one.  The request is silently ignored.  This
		simplifies "reset everything" loops.

		If calling code wishes to know if a channel has a bypass
		capacitor, test the value of .bypass_address:  None = this
		channel does not have a bypass capacitor.
		"""
		raise NotImplementedError

	@bypass.setter
	def bypass(self, boolean):
		# bypass capacitor is turned on and off with bit 0.
		# silently ignore requests to turn on or off bypass
		# capacitors on channels that don't have them.
		if self.bypass_address is not None:
			self.programmer.write_addr(self.bypass_address, 1 if boolean else 0)

	@property
	def physical(self):
		"""
		Physical location of this channel within the programmer.
		Value is a tuple:  (pin driver group #, DAC chip identifier
		#, hybrid identifier #, channel # on hybrid).  This assists
		with the interpretation of self test results, e.g., are all
		of the malfunctioning channels on the same pin driver group
		plug-in board, are they on the same hybrid module?
		"""
		return (
			# group # printed on motherboard PCB
			self.channel // 8,
			# DAC chip ident., U# printed on channel driver PCB
			self.channel % 8 + 1,
			# hybrid ident., H# printed on channel driver PCB
			(self.channel % 8) // 2 + 1,
			# hybrid channel number (as numbered by me for my
			# hybrid tester jig)
			(self.channel % 8) % 2
		)


