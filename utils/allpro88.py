	def echo(self, val):
		"""
		Echo a 4 digit number (USB loop-back test).
		"""
		assert 0 <= val <= 0xffff
		val, = self.write_command("E%04X" % val)
		return val


	def write_addr(self, addr, val):
		"""
		Write value to register.

		NOTE NOTE NOTE:  physical damage will occur if the wrong
		value is written to the wrong address.  by writing an
		unfortunate value to a pin configuration register, a pin
		might be connected to both a supply voltage and ground
		simultaneously, destroying the pin driver electronics.  for
		testing purposes, writing 0 to any address is safe.  this
		always corresponds to the "disabled" or "turned off"
		setting for any register.  other values should only be
		written after carefully consulting the documentation.
		"""
		assert 0 <= addr <= 0x0fff
		assert 0 <= val <= 0xff
		self.write_command("=%04X%02X" % (addr, val))


	def read_addr(self, addr):
		"""
		Read value from register.
		"""
		assert 0 <= addr <= 0x0fff
		val, = self.write_command("?%04X" % addr)
		assert 0 <= val <= 0xff
		return val


	@property
	def socket_module_id(self):
		"""
		Returns the ID of the socket module installed in the
		programmer, or 0xff is no module is installed.
		"""
		return self.read_addr(0x0280)


	@property
	def system_id(self):
		# in the ALLPRO88 documentation some command line
		# diagnostic tools are shown producing example output
		# reporting a "system ID" of 0x3 and "adapter ID" of 0x11.
		# other examples show an "analog ID" of 0x03.  the "adapter
		# ID" definitely refers to the socket board ID.  mine is
		# 0x11, like the examples (kevtris' is 0x81).  but where do
		# the "system ID" and "analog ID" come from?  are they
		# synonyms for the same number?  kevtris' documentation
		# describes an A1STAT register (status register on the
		# analogue 1 board), whose low nibble he says is hard-wired
		# to report 0x3, curiously the same as both the "system ID"
		# and "analog ID" shown in the examples in the
		# documentation.  my unit also reports 0x3 in that nibble,
		# and the circuit responsible for that behaviour can be
		# seen in the schematics in the serivce manual, where there
		# is a comment written about the value being hard-wired to
		# 0x3.  is this the "system ID" and/or "analog ID"?  are
		# they synonyms?  I'm guessing they are, and it is, and
		# that's what this descriptor returns.
		#
		# Logical Devices made other devices similar to the
		# ALLPRO88, including an older ALLPRO that had only 4
		# channels per pin driver group, not 8, and a single 96 pin
		# DIN connector to the socket module, instead of the two of
		# the ALLPRO88.  it also lacked the ability to generate TTL
		# clock signals, and maybe some other features that I can't
		# remember right now.  socket modules for the older ALLPRO
		# are compatible with the ALLPRO88, they simply mate with
		# the one DIN connector.  the ALLPRO88's other connector
		# (which only carries the higher-numbered channel outputs,
		# and nothing else) is left with nothing plugged into it.
		# my guess is that all ALLPRO-like units look exactly the
		# same to the host PC:  a memory mapped array of registers
		# that control the pin drivers.  they probably used the
		# same ISA interface board for all such systems, and this
		# ID might be how to tell which kind of unit is plugged
		# into the computer, because there might be literally no
		# other way to tell the difference.  if those guesses are
		# correct, then this library and the USB interface board
		# will work just fine with an ALLPRO (non-88), perhaps with
		# just a few features disabled.  in that case, this library
		# should use this system ID code to enable or disable the
		# appropriate features.  someone with an ALLPRO (non-88)
		# would need to do some research on that.

		return self.read_addr(0x0300) & 0xf

